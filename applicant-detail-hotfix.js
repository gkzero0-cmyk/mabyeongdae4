  function getOverride(userId) {
    const key = String(userId || '').trim().toLowerCase();
    const value = OVERRIDES[key];
    return value ? { ...value } : null;
  }

  function applyOverride(userId, parsed) {
    const base = parsed && typeof parsed === 'object' ? { ...parsed } : {};
    const override = getOverride(userId);
    if (!override) return base;
    if (Object.prototype.hasOwnProperty.call(override, 'experience')) base.minecraftExperience = override.experience;
    if (Object.prototype.hasOwnProperty.call(override, 'reason')) base.reason = override.reason;
    return base;
  }

  function extractUrls(text) {
    const matches = String(text || '').match(/https?:\/\/[^\s<>"']+/gi) || [];
    const seen = new Set();
    const out = [];
    for (const raw of matches) {
      const url = raw.replace(/[),.;!?。！？、]+$/u, '');
      if (!url || seen.has(url)) continue;
      seen.add(url);
      out.push(url);
    }
    return out;
  }

  return {
    getOverride,
    applyOverride,
    extractUrls
  };
